import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
await import('../p0/build.mjs');
const root = resolve(import.meta.dirname,'..'), layout = resolve(root,'layout');
const code = await readFile(resolve(root,'p0/dist/layout-client.js'));
const digest = createHash('sha256').update(code).digest('hex').slice(0,12);
const path = resolve(layout,'package.json'), manifest = JSON.parse(await readFile(path,'utf8'));
const previous = manifest.exports['./shell-entry'], entry = './lib/entry-' + digest + '.js';
const patchPath = resolve(root,'cordis.patch.yml'), patch = await readFile(patchPath,'utf8');
const oldReference = './layout/' + previous.slice(2), newReference = './layout/' + entry.slice(2);
if (patch.split(oldReference).length !== 2) throw Error('Missing/nonunique dual-layout overlay anchor');
await mkdir(resolve(layout,'lib'),{recursive:true});
await writeFile(resolve(layout,'lib/client.js'),code);
await writeFile(resolve(layout,entry),'// Content-keyed client layout identity.\nexport { apply } from "./index.js";\n');
manifest.exports['./shell-entry']=entry;
await writeFile(path,JSON.stringify(manifest,null,2)+'\n');
await writeFile(patchPath,patch.replace(oldReference,newReference));
console.log('Prepared dual layout',entry,'without loading any profile.');
