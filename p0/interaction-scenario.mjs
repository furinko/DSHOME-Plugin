import {setMode} from './interaction-helpers.mjs';
import {runDragFiles} from './drag-files-scenario.mjs';
import assert from 'node:assert/strict';
export async function runInteractionScenario(page) {
  await setMode(page,'工作台');
  const scene = page.locator('.p0-full-scene:not([hidden])');
  const layout = scene.getByRole('button', { name: '布局选项', exact: true });
  assert.equal(await scene.getByRole('button', { name: '保存布局', exact: true }).count(), 0);
  await layout.click();
  await scene.getByRole('button', { name: '保存布局', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await layout.getAttribute('aria-expanded'), 'false');
  assert.equal(await layout.evaluate(n => document.activeElement === n), true);
  await layout.click();
  await scene.locator('.wb-heading').click();
  assert.equal(await layout.getAttribute('aria-expanded'), 'false');
  const open = scene.getByRole('button', { name: '快速打开文件', exact: true });
  await open.click();
  const dialog = scene.getByRole('dialog', { name: '快速打开文件', exact: true });
  const input = dialog.getByRole('combobox');
  await input.fill('example.md'); await input.press('Home');
  assert.equal(await input.evaluate(n => n.selectionStart), 0);
  await input.press('End'); assert.equal(await input.evaluate(n => n.selectionStart), 10);
  await input.press('Escape');
  assert.equal(await open.evaluate(n => document.activeElement === n), true);
  await open.press('Control+Shift+p');
  await scene.getByRole('dialog', { name: '命令面板', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await scene.getByRole('button', { name: '新建内容', exact: true }).click();
  await scene.getByRole('button', { name: '新建便笺', exact: true }).click();
  const note = scene.locator('.wb-note:visible');
  await note.fill('保留这份草稿');
  const panel = note.locator('xpath=ancestor::article');
  const close = panel.locator('.wb-tab-item:has([role=tab][aria-selected=true])').getByRole('button', {name:/关闭标签/});
  page.once('dialog', d => d.dismiss()); await close.click();
  assert.equal(await note.inputValue(), '保留这份草稿');
  page.once('dialog', d => d.accept()); await close.click();
  assert.equal(await note.count(), 0);
  assert.equal(await page.getByRole('group', { name: '侧栏工具', exact: true }).count(), 0);
  const tab = scene.locator('.wb-tab-item:visible').first();
  const colors = await tab.evaluate(n => ({ outer: getComputedStyle(n).backgroundColor, tab: getComputedStyle(n.querySelector('[role=tab]')).backgroundColor, close: getComputedStyle(n.querySelector('.wb-tab-close')).backgroundColor, width: n.querySelector('.wb-tab-close').getBoundingClientRect().width }));
  assert.equal(colors.tab, 'rgba(0, 0, 0, 0)'); assert.equal(colors.close, 'rgba(0, 0, 0, 0)'); assert.equal(colors.width, 24);
  await page.screenshot({path:'test-output/tabs-workbench.png'});
  await tab.screenshot({path:'test-output/tab-detail.png'});
  await page.evaluate(()=>window.testP0.ctx.theme.setTheme('dark'));
  await page.waitForFunction(()=>document.body.hasAttribute('data-ds-dark-theme'));
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.p0-full-scene:not([hidden]) .wb-tab-item [aria-selected=true]')).color==='rgb(230, 237, 247)');
  assert.equal(await tab.locator('[role=tab]').evaluate(n=>getComputedStyle(n).color),'rgb(230, 237, 247)');
  await tab.screenshot({path:'test-output/tab-detail-dark.png'});
  await page.evaluate(()=>window.testP0.ctx.theme.setTheme('light'));
  await page.waitForFunction(()=>!document.body.hasAttribute('data-ds-dark-theme'));
  const dragFiles=await runDragFiles(page); return { dragFiles, layoutDisclosure:true, escapeRestoresFocus:true, outsideClickDismisses:true, directFileOpen:true, textHomeEnd:true, commandShortcut:true, tabCloseCancelPreservesDraft:true, confirmedClose:true };
}
